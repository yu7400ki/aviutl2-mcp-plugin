//! SDK 側のレンダリング経路を表す境界。
//!
//! # 完了は戻り値ではなく受け皿で受け取る
//!
//! 読み取りも編集も、SDK の呼び出しが戻った時点で結果が手に入る。レンダリングの
//! 投入はタスクを積むだけで戻り、結果はホストのレンダリング用スレッドから届く。
//! そのため [`RenderHost::request_scene_video`] は結果を返さず、**呼び出し側が
//! 用意した受け皿を引数に取る**。
//!
//! 受け皿を引数にするのは、コールバックへ渡すクロージャの組み立てを SDK 境界の
//! 内側へ閉じるためである。閉じておけば、境界の実装を差し替えるだけで「同期で
//! 埋める」「遅れて埋める」「一度も埋めない」「二度埋める」を再現でき、
//! レンダリングの全経路を AviUtl2 無しで確かめられる。
//!
//! # 区間へ入る口を持たない
//!
//! この境界には参照区間・編集区間へ入るメソッドが無い。完了待ちは参照ロック・
//! 編集ロックの下で呼ぶとデッドロックし得るためであり、必要な編集情報は区間の
//! 外で取る [`RenderHost::edit_info`] から得る。**口が無いことが、レンダリング
//! 経路が区間へ入らないことの保証である。**

use crate::read::host::{EditState, HostEditInfo};
use crate::render::error::RenderError;
use crate::render::slot::RenderSlot;
use std::sync::Arc;

/// 編集ハンドルが提供するレンダリング経路。
pub trait RenderHost: Send + Sync {
    /// レンダリング API を呼び出せる状態か。
    ///
    /// これが偽の間、他のメソッドを呼んではならない。SDK は準備前の呼び出しを
    /// 「失敗を返す」のではなく打ち切りで落とす。
    fn is_ready(&self) -> bool;

    /// 現在の編集状態。
    fn edit_state(&self) -> Result<EditState, RenderError>;

    /// 区間の外で取得する編集情報。
    ///
    /// シーン ID・画像の大きさ・最終フレームを得る。**この呼び出しは落ち得る**
    /// ため、呼び出し側が捕捉層で包むことを前提にする。
    fn edit_info(&self) -> Result<HostEditInfo, RenderError>;

    /// レンダリングタスクを投入する。
    ///
    /// **成功しても完了が届く保証は無い。** 投入したタスクを取り消す手段も無い
    /// ため、呼び出し側は必ず期限を付けて待つ。
    ///
    /// 実装は `slot` を捕捉したクロージャを組み立ててホストへ渡し、完了時に
    /// [`crate::render::slot::deliver_frame_guarded`] を通す。クロージャが捕捉して
    /// よいのは `slot` と要求したフレーム番号だけである。
    fn request_scene_video(&self, frame: u32, slot: Arc<RenderSlot>) -> Result<(), RenderError>;

    /// 投入済みタスクが全て完了するまで待つ。
    ///
    /// **区間の外でのみ呼ぶ。** 期限を取らず、個別のタスクも指定できない。
    /// 呼び出せる状態でなければ何もせず戻る。
    fn wait_all_tasks(&self);
}
